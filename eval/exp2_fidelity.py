def source_geometry(series_dir: Path):
    """Read the source series and map SOP Instance UID to slice index.

    The common frame for every comparison in this experiment is the source
    DICOM grid, because that is the frame the host renders in and the frame the
    SEG references. Ordering comes from GDCM's geometric sort, which is what
    the adapter's exporter uses to build its reference volume.
    """
    import pydicom
    import SimpleITK as sitk

    reader = sitk.ImageSeriesReader()
    files = reader.GetGDCMSeriesFileNames(str(series_dir))
    if not files:
        raise RuntimeError(f"no readable DICOM series in {series_dir}")
    reader.SetFileNames(files)
    reference = reader.Execute()

    uid_to_index: dict[str, int] = {}
    for index, path in enumerate(files):
        header = pydicom.dcmread(path, stop_before_pixels=True)
        uid_to_index[str(header.SOPInstanceUID)] = index

    size = reference.GetSize()
    return reference, uid_to_index, (size[2], size[1], size[0])


def resample_to_source(mask_path: Path, reference) -> np.ndarray:
    """Put a native NIfTI mask on the source grid, as the exporter does.

    Identical operation and identical interpolator to
    run_segment._export_dicom_seg, so this array is what the encoder would have
    been handed. Using anything else here would measure our resampler against
    the adapter's rather than measuring the abstraction.
    """
    import SimpleITK as sitk

    mask = sitk.ReadImage(str(mask_path))
    mask = sitk.Resample(mask, reference, sitk.Transform(),
                         sitk.sitkNearestNeighbor, 0, mask.GetPixelID())
    return sitk.GetArrayFromImage(mask) > 0


def load_native_masks(mask_dir: Path) -> dict[str, Path]:
    return {p.name[: -len(".nii.gz")]: p for p in sorted(mask_dir.glob("*.nii.gz"))}


