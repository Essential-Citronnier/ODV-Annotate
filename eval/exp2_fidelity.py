def worker_convert(args: argparse.Namespace) -> int:
    """DICOM series -> NIfTI, using TotalSegmentator's own converter.

    The native path must be fed the same volume the plugin path is fed. The
    adapter hands TotalSegmentator a DICOM directory, and TotalSegmentator
    converts it internally with dicom2nifti; calling that same converter here
    keeps the only difference between the two paths the abstraction itself.
    """
    from totalsegmentator.dicom_io import dcm_to_nifti

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    dcm_to_nifti(str(args.series), out, tmp_dir=out.parent, verbose=False)
    return 0


def worker_native(args: argparse.Namespace) -> int:
    """TotalSegmentator called directly on a NIfTI -- path B."""
    from totalsegmentator.python_api import totalsegmentator

    totalsegmentator(input=str(args.input), output=str(args.output),
                     task="total", fast=args.fast, ml=False, quiet=True)
    return 0


def worker_probe_thickness(args: argparse.Namespace) -> int:
    """Try to encode a SEG for a series lacking SliceThickness; report the outcome.

    Run as a child so the caller controls, via ODV_EXP2_SANDBOX, whether the
    evaluation's pixel-measures fallback is installed. Exit 0 means the encode
    succeeded.
    """
    reference, _, shape = source_geometry(Path(args.series))
    mask = np.zeros(shape, dtype=bool)
    mask[1:4, 8:20, 8:20] = True
    try:
        _encode_masks_via_adapter(Path(args.series), {"alpha": mask}, reference,
                                  Path(args.output))
    except Exception as exc:  # noqa: BLE001 -- the failure is the observation
        print(f"PROBE_RESULT {type(exc).__name__}: {exc}")
        return 1
    print("PROBE_RESULT encoded")
    return 0


def worker_encode(args: argparse.Namespace) -> int:
    """Encode masks with the ADAPTER's own exporter, for the round-trip test.

    Imports run_segment and calls the exporter the shipping adapter calls. A
    reimplementation here would test this file against itself; the claim is
    about the code the host actually runs.
    """
    sys.path.insert(0, str(REPO_ROOT / "plugins"))
    sys.path.insert(0, str(REPO_ROOT / "plugins" / "totalseg"))
