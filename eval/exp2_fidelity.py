#!/usr/bin/env python3
# exp2_fidelity.py
# OpenDicomViewer -- plugin layer evaluation, Experiment 2.
#
# Claim under test: routing a segmentation model through the ODV plugin
# abstraction is LOSSLESS. The abstraction is a pipeline --
#
#     DICOM series -> adapter -> DICOM SEG -> host decode -> masks
#
# -- and the question is whether the masks that come out the far end are the
# masks TotalSegmentator produced. TotalSegmentator's segmentation ACCURACY is
# not the subject here; it is published, it is not our contribution, and
# nothing in this file should be read as a claim about it.
"""Pipeline-fidelity comparison of the plugin path against the native path.

Three measurements, because a single A-vs-B Dice cannot attribute a
disagreement to the thing we are claiming about:

  (i)   determinism control -- the native model run twice on byte-identical
        input. Any disagreement here is the model's own nondeterminism and
        bounds what (iii) can possibly show. Without it, a Dice of 0.998 in
        (iii) is uninterpretable: it could be our abstraction or it could be
        nnU-Net.

  (ii)  SEG round trip -- the same in-memory masks encoded to DICOM SEG by the
        adapter's own exporter and decoded back by a reimplementation of the
        host's Swift reader. Zero model variance enters this measurement, so it
        isolates the abstraction and is where "lossless" is actually decided.

  (iii) end to end -- the plugin adapter invoked exactly as the host invokes it
        (PLUGIN_PROTOCOL.md section 4), against a native run on the same CT.
        This is the number a reader wants, and it inherits (i)'s noise floor.

Every structure is reported separately. A mean Dice of 0.99 over 80 structures
hides a structure at 0.4, and the point of the experiment is to find exactly
that kind of failure before a reviewer does.

Usage:
    PYTHONPATH=eval python eval/exp2_fidelity.py \\
        --data-root .eval/data/tcia --out eval/results/exp2_fidelity.jsonl \\
        --python /path/to/seg-engine/.venv/bin/python
"""
