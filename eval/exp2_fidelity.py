def decode_seg_like_host(seg_path: Path, uid_to_index: dict[str, int],
                         volume_shape: tuple[int, int, int]) -> dict[str, np.ndarray]:
    """Decode a binary DICOM SEG the way the Swift host decodes it.

    This deliberately mirrors DICOMAnnotationObject.parseSegmentation rather
    than using a library reader. The claim being tested is about the round trip
    the host actually performs, and a discrepancy between the encoder and the
    host's own decoder is exactly the defect this experiment exists to catch --
    a library reader that silently repairs it would hide the bug.

    Reproduced from the Swift, in order:
      - refuse anything but SegmentationType BINARY, BitsAllocated 1,
        SamplesPerPixel 1;
      - iterate min(NumberOfFrames, len(PerFrameFunctionalGroupsSequence));
      - read each frame's bits from a continuous LSB-first bit stream at offset
        frameIndex * Rows * Columns;
      - take the segment from SegmentIdentificationSequence and the source
        slice from DerivationImageSequence -> SourceImageSequence.

    The host places a frame on a slice by referenced SOP Instance UID alone; it
    never uses ImagePositionPatient. With omit_empty_frames=True the frame list
    is sparse, so that mapping carries the whole geometry of the result.
    """
    import pydicom

    dataset = pydicom.dcmread(str(seg_path))
    if str(getattr(dataset, "SegmentationType", "")).upper() != "BINARY":
        raise ValueError("host reader accepts only SegmentationType BINARY")
    if int(dataset.BitsAllocated) != 1 or int(dataset.SamplesPerPixel) != 1:
        raise ValueError("host reader accepts only 1-bit single-sample frames")

    rows, columns = int(dataset.Rows), int(dataset.Columns)
    pixels_per_frame = rows * columns
    labels = {int(s.SegmentNumber): str(getattr(s, "SegmentLabel", ""))
              for s in dataset.SegmentSequence}

    per_frame = list(getattr(dataset, "PerFrameFunctionalGroupsSequence", []))
    declared = int(getattr(dataset, "NumberOfFrames", 1))
    frame_count = min(declared, len(per_frame) or declared)

    packed = np.frombuffer(dataset.PixelData, dtype=np.uint8)
    volumes: dict[str, np.ndarray] = {}
    unplaced = 0

    for frame_index in range(frame_count):
        bit_start = frame_index * pixels_per_frame
        byte_start, byte_end = bit_start // 8, (bit_start + pixels_per_frame + 7) // 8
        if byte_end > packed.size:
            break
        # bitorder="little" is the DICOM packing order and matches the Swift's
        # (byte >> (bitIndex % 8)) & 1.
        bits = np.unpackbits(packed[byte_start:byte_end], bitorder="little")
        offset = bit_start - byte_start * 8
        frame = bits[offset:offset + pixels_per_frame].reshape(rows, columns).astype(bool)

        item = per_frame[frame_index]
        segment_number = int(item.SegmentIdentificationSequence[0]
                             .ReferencedSegmentNumber)
        name = labels.get(segment_number) or f"segment_{segment_number}"

        referenced_uid = None
        for derivation in getattr(item, "DerivationImageSequence", []):
            for source in getattr(derivation, "SourceImageSequence", []):
                uid = getattr(source, "ReferencedSOPInstanceUID", None)
                if uid:
                    referenced_uid = str(uid)
                    break
            if referenced_uid:
                break

        index = uid_to_index.get(referenced_uid) if referenced_uid else None
        if index is None:
            unplaced += 1
            continue
        volume = volumes.get(name)
        if volume is None:
            volume = np.zeros(volume_shape, dtype=bool)
            volumes[name] = volume
        volume[index] |= frame

    if unplaced:
        # Surfaced rather than swallowed: a frame the host cannot place is a
        # frame the host will not draw, which is silent data loss on screen.
        volumes["__unplaced_frames__"] = np.array(unplaced)
    return volumes


