def compare(reference: dict[str, np.ndarray], candidate: dict[str, np.ndarray],
            voxel_ml: float) -> list[dict[str, Any]]:
    """Per-structure Dice and voxel-count delta over the union of structures.

    The union, not the intersection: a structure present in one path and absent
    from the other is the most interesting possible disagreement, and
    intersecting the key sets would delete exactly that evidence. harness.dice
    scores two empty masks as 1.0, so a structure genuinely absent from both
    does not drag the distribution down.
    """
    rows: list[dict[str, Any]] = []
    for name in sorted(set(reference) | set(candidate)):
        a = reference.get(name)
        b = candidate.get(name)
        a_count = int(a.sum()) if a is not None else 0
        b_count = int(b.sum()) if b is not None else 0
        if a is None:
            a = np.zeros_like(b)
        if b is None:
            b = np.zeros_like(a)
        rows.append({
            "structure": name,
            "dice": round(dice(a, b), 6),
            "reference_voxels": a_count,
            "candidate_voxels": b_count,
            "voxel_delta": b_count - a_count,
            "volume_delta_ml": round((b_count - a_count) * voxel_ml, 4),
            "in_reference_only": b_count == 0 and a_count > 0,
            "in_candidate_only": a_count == 0 and b_count > 0,
        })
    return rows


def summarise(rows: list[dict[str, Any]]) -> dict[str, Any]:
    if not rows:
        return {"structures": 0}
    dices = np.array([r["dice"] for r in rows], dtype=float)
    return {
        "structures": len(rows),
        "dice_mean": round(float(dices.mean()), 6),
        "dice_min": round(float(dices.min()), 6),
        "dice_p05": round(float(np.percentile(dices, 5)), 6),
        "exact_agreement": int((dices >= 1.0).sum()),
        "below_0999": int((dices < 0.999).sum()),
        "worst": sorted(rows, key=lambda r: r["dice"])[:5],
    }


