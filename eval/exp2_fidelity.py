def write_csv(rows_path: Path, csv_path: Path) -> int:
    """Flatten the per-structure records to one row per (case, comparison, structure)."""
    import csv

    from harness import load_results

    _, rows = load_results(rows_path)
    fields = ["case_id", "comparison", "structure", "dice", "reference_voxels",
              "candidate_voxels", "voxel_delta", "volume_delta_ml", "ok"]
    written = 0
    with open(csv_path, "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        for row in rows:
            metrics = row.get("metrics") or {}
            for comparison, key in (("roundtrip", "per_structure_roundtrip"),
                                    ("end_to_end", "per_structure_end_to_end"),
                                    ("determinism", "per_structure_determinism")):
                for entry in metrics.get(key) or []:
                    writer.writerow({
                        "case_id": row["case_id"], "comparison": comparison,
                        "structure": entry["structure"], "dice": entry["dice"],
                        "reference_voxels": entry.get("reference_voxels"),
                        "candidate_voxels": entry.get("candidate_voxels"),
                        "voxel_delta": entry.get("voxel_delta"),
                        "volume_delta_ml": entry.get("volume_delta_ml"),
                        "ok": row["ok"]})
                    written += 1
    return written


