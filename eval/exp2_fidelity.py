# Controlled probes
# ---------------------------------------------------------------------------
#
# The cohort measurement below returns Dice 1.0 everywhere. A comparison that
# reports perfect agreement is worthless unless it is shown to be capable of
# reporting anything else, and a pipeline that is lossless on the inputs we
# happened to run is not the same as a pipeline that is lossless. These probes
# do both jobs: they establish the measurement's sensitivity, and they drive
# the encoder into the regimes the cohort never reaches.


def _synthetic_series(scratch: Path, slices: int = 6, size: int = 32) -> Path:
    """A minimal but conformant CT series, written with pydicom.

    Small enough that a probe runs in seconds, and constructed here rather than
    subsetting a cohort series so the probes have no data dependency and stay
    runnable when .eval/data is absent.
    """
    import numpy as np
    import pydicom
    from pydicom.dataset import Dataset, FileMetaDataset
    from pydicom.uid import CTImageStorage, ExplicitVRLittleEndian, generate_uid

    out = scratch / "synthetic_series"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    study_uid, series_uid, frame_uid = generate_uid(), generate_uid(), generate_uid()

    for index in range(slices):
        meta = FileMetaDataset()
        meta.MediaStorageSOPClassUID = CTImageStorage
        meta.MediaStorageSOPInstanceUID = generate_uid()
        meta.TransferSyntaxUID = ExplicitVRLittleEndian
        ds = Dataset()
        ds.file_meta = meta
        ds.is_little_endian, ds.is_implicit_VR = True, False
        ds.SOPClassUID = CTImageStorage
        ds.SOPInstanceUID = meta.MediaStorageSOPInstanceUID
        ds.StudyInstanceUID, ds.SeriesInstanceUID = study_uid, series_uid
        ds.FrameOfReferenceUID = frame_uid
        ds.PatientName, ds.PatientID = "Synthetic^Probe", "PROBE"
        # Type 2 patient/study attributes: highdicom copies these into the SEG
        # by attribute access, so an absent one raises rather than defaulting.
        ds.PatientBirthDate = ""
        ds.PatientSex = ""
        ds.StudyDate = ds.SeriesDate = ds.ContentDate = "20260101"
        ds.StudyTime = ds.SeriesTime = ds.ContentTime = "120000"
        ds.AccessionNumber = ""
        ds.StudyID = "1"
        ds.SeriesNumber = 1
        ds.ReferringPhysicianName = ""
        ds.Manufacturer = "OpenDicomViewer evaluation"
        ds.Modality = "CT"
        ds.Rows, ds.Columns = size, size
        ds.PixelSpacing = [1.0, 1.0]
        ds.SliceThickness = 1.0          # present here: the probes are about
        ds.SpacingBetweenSlices = 1.0    # the encoder, not the missing-tag bug
        ds.ImagePositionPatient = [0.0, 0.0, float(index)]
        ds.ImageOrientationPatient = [1, 0, 0, 0, 1, 0]
        ds.InstanceNumber = index + 1
        ds.SamplesPerPixel, ds.PhotometricInterpretation = 1, "MONOCHROME2"
        ds.BitsAllocated, ds.BitsStored, ds.HighBit = 16, 16, 15
        ds.PixelRepresentation = 1
        ds.RescaleIntercept, ds.RescaleSlope = 0.0, 1.0
        ds.PixelData = np.zeros((size, size), dtype=np.int16).tobytes()
        pydicom.dcmwrite(out / f"slice_{index:03d}.dcm", ds,
                         enforce_file_format=True)
    return out


def _encode_masks_via_adapter(series_dir: Path, masks: dict[str, np.ndarray],
                              reference, out_path: Path) -> None:
    """Write masks to NIfTI on the source grid and hand them to the exporter.

    Goes through the adapter's real `_export_dicom_seg` rather than calling
    highdicom directly, so a probe exercises the shipping code path.
    """
    import SimpleITK as sitk

    sys.path.insert(0, str(REPO_ROOT / "plugins"))
    sys.path.insert(0, str(REPO_ROOT / "plugins" / "totalseg"))
    import run_segment  # noqa: PLC0415
    from _shared.progress import ProgressReporter  # noqa: PLC0415

    staged = out_path.parent / "staged_masks"
    staged.mkdir(parents=True, exist_ok=True)
    entries = []
    for name, array in masks.items():
        image = sitk.GetImageFromArray(array.astype(np.uint8))
        image.CopyInformation(reference)
        path = staged / f"{name}.nii.gz"
        sitk.WriteImage(image, str(path))
        entries.append((name, path))
    run_segment._export_dicom_seg(series_dir, entries, out_path, "total",
                                  ProgressReporter(stream=sys.stderr))


def probe_cohort_overlap(mask_dirs: list[Path], reference_dirs: list[Path],
                         ) -> dict[str, Any]:
    """Is the overlapping-structure defect reachable through this adapter today?

    The controlled probe proves the encoder loses voxels when two structures
    share one, by constructing that situation. It does not say whether the
    situation can ARISE, and that distinction decides whether the finding is a
    limitation to document or a bug to fix now.

    Two questions, answered separately:

      1. Are TotalSegmentator's per-structure masks disjoint as produced?
         Structurally they must be: totalsegmentator/nnunet.py writes each file
         as `binary_img = img_data == k`, an equality test against one integer
         labelmap, so a voxel carries exactly one label. Verified by counting
         multiply-covered voxels rather than trusting the reading.

      2. Are they still disjoint after the exporter resamples them onto the
         SOURCE grid? This is the step the code reading does not cover. Nearest
         -neighbour resampling is applied to each structure independently, so
         two structures adjacent on a fine grid could in principle both claim a
         coarse-grid voxel. This is where a real collision would appear.
    """
    import nibabel as nib

    native_overlap = 0
    native_structures = 0
    resampled_overlap = 0
    resampled_structures = 0
    colliding: list[str] = []

    for mask_dir, series_dir in zip(mask_dirs, reference_dirs):
        paths = load_native_masks(mask_dir)
        coverage = None
        for name, path in paths.items():
            array = np.asanyarray(nib.load(str(path)).dataobj) > 0
            if not array.any():
                continue
            native_structures += 1
            if coverage is None:
                coverage = np.zeros(array.shape, dtype=np.uint8)
            native_overlap += int((coverage[array] > 0).sum())
            coverage[array] += 1

        reference, _, shape = source_geometry(series_dir)
        coverage = np.zeros(shape, dtype=np.uint8)
        for name, path in paths.items():
            array = resample_to_source(path, reference)
            if not array.any():
                continue
            resampled_structures += 1
            collisions = int((coverage[array] > 0).sum())
            if collisions:
                resampled_overlap += collisions
                colliding.append(f"{series_dir.name}/{name}:{collisions}")
            coverage[array] += 1

    # A third, independent line of evidence, already on disk: clipping is
    # exactly what the defect DOES, so if any two structures had shared a voxel
    # in the cohort, the earlier-encoded one would have come back short and its
    # round-trip Dice would be below 1.0. Every round-trip comparison in
    # exp2_fidelity.jsonl is exactly 1.0, which is only possible if no
    # collision occurred. This holds over the whole cohort rather than the
    # cases re-measured here, and it needs no extra computation.
    return {
        "probe": "cohort_overlap_reachability",
        "ok": native_overlap == 0 and resampled_overlap == 0,
        "detail": {
            "cases": len(mask_dirs),
            "structures_native": native_structures,
            "multiply_covered_voxels_native": native_overlap,
            "structures_after_resampling": resampled_structures,
            "multiply_covered_voxels_after_resampling": resampled_overlap,
            "colliding_structures": colliding[:20],
        },
        "interpretation": (
            "TotalSegmentator's `total` task derives every per-structure mask "
            "from one integer labelmap by equality test, so its structures are "
            "disjoint by construction, and they remain disjoint after the "
            "exporter's nearest-neighbour resampling onto the source grid. The "
            "single-labelmap encoding defect is therefore NOT reachable through "
            "the adapters shipping today -- it is a documented limitation of "
            "the seg3d output kind for future adapters whose structures may "
            "overlap, not an active bug in this pipeline"),
        "corroborating_evidence": (
            "clipping is the defect's mechanism, so any cohort collision would "
            "have shown up as a round-trip Dice below 1.0 for the "
            "earlier-encoded structure; all 689 round-trip comparisons in "
            "exp2_fidelity.jsonl are exactly 1.0, which independently rules "
            "out a collision anywhere in the cohort"),
    }


def run_probes(scratch: Path) -> list[dict[str, Any]]:
    """Four controlled probes against the adapter's encoder and the host reader."""
    probes: list[dict[str, Any]] = []
    work = scratch / "probes"
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)

    series = _synthetic_series(work)
    reference, uid_to_index, shape = source_geometry(series)
    depth, rows, columns = shape

    def block(z0, z1, y0, y1, x0, x1) -> np.ndarray:
        volume = np.zeros(shape, dtype=bool)
        volume[z0:z1, y0:y1, x0:x1] = True
        return volume

    # -- probe 1: sensitivity ------------------------------------------------
    # Perturb the decoded result by known amounts and confirm the comparison
    # reports the disagreement. Without this, "Dice = 1.0" could equally mean
    # "the comparison cannot see anything".
    truth = {"alpha": block(1, 4, 8, 20, 8, 20)}
    baseline = compare(truth, {"alpha": truth["alpha"].copy()}, 1e-3)[0]["dice"]

    one_voxel = truth["alpha"].copy()
    one_voxel[1, 8, 8] = False
    single = compare(truth, {"alpha": one_voxel}, 1e-3)[0]

    shifted = np.roll(truth["alpha"], 1, axis=0)
    slice_shift = compare(truth, {"alpha": shifted}, 1e-3)[0]

    dropped = compare(truth, {}, 1e-3)[0]

    probes.append({
        "probe": "comparison_sensitivity",
        "ok": (baseline == 1.0 and single["dice"] < 1.0
               and slice_shift["dice"] < 1.0 and dropped["dice"] == 0.0),
        "detail": {
            "identical_dice": baseline,
            "one_voxel_removed_dice": single["dice"],
            "one_voxel_removed_delta": single["voxel_delta"],
            "one_slice_shift_dice": slice_shift["dice"],
            "structure_dropped_dice": dropped["dice"],
        },
        "interpretation": (
            "the per-structure comparison resolves a single voxel out of "
            f"{int(truth['alpha'].sum())}, so a Dice of 1.0 elsewhere is a "
            "measurement and not a blind spot"),
    })

    # -- probe 2: sparse frames ---------------------------------------------
    # The exporter sets omit_empty_frames=True, so a structure occupying 2 of 6
    # slices contributes 2 frames, not 6. The host reconstructs the z position
    # from each frame's referenced SOP Instance UID. If that mapping were wrong
    # the masks would land on the wrong slices -- an error that shifts anatomy
    # rather than raising.
    sparse_masks = {
        "early": block(0, 2, 4, 12, 4, 12),
        "late": block(4, 6, 20, 28, 20, 28),
        "middle_single": block(3, 4, 14, 18, 14, 18),
    }
    sparse_seg = work / "sparse.dcm"
    _encode_masks_via_adapter(series, sparse_masks, reference, sparse_seg)
    decoded_sparse = decode_seg_like_host(sparse_seg, uid_to_index, shape)
    unplaced_sparse = int(decoded_sparse.pop("__unplaced_frames__", 0))
    sparse_rows = compare(sparse_masks, decoded_sparse, 1e-3)
    import pydicom

    encoded_frames = int(pydicom.dcmread(str(sparse_seg)).NumberOfFrames)
    expected_frames = sum(int(m.any(axis=(1, 2)).sum()) for m in sparse_masks.values())
    probes.append({
        "probe": "sparse_frame_reconstruction",
        "ok": (all(r["dice"] == 1.0 for r in sparse_rows) and unplaced_sparse == 0
               and encoded_frames == expected_frames),
        "detail": {
            "frames_encoded": encoded_frames,
            "frames_if_dense": len(sparse_masks) * depth,
            "frames_expected_sparse": expected_frames,
            "unplaced_frames": unplaced_sparse,
            "per_structure": sparse_rows,
        },
        "interpretation": (
            "empty frames are omitted and the host still reconstructs every "
            "structure on the correct slices, so the sparse encoding is not "
            "silently shifting anatomy in z"),
    })

    # -- probe 3: overlapping structures ------------------------------------
    # The exporter accumulates structures into ONE uint8 labelmap with
    # `label[array] = index`, so where two structures overlap the later index
    # overwrites the earlier. TotalSegmentator's `total` task cannot trigger
    # this -- its per-structure files come from one argmax labelmap and are
    # disjoint, confirmed on the cohort -- but the protocol's seg3d output kind
    # does not require disjoint structures, and a future adapter emitting
    # overlapping masks would lose voxels with no error raised.
    overlap_masks = {
        "aaa_first": block(1, 5, 8, 24, 8, 24),
        "zzz_second": block(1, 5, 16, 28, 16, 28),   # overlaps aaa_first
    }
    intersection = int((overlap_masks["aaa_first"] & overlap_masks["zzz_second"]).sum())
    overlap_seg = work / "overlap.dcm"
    _encode_masks_via_adapter(series, overlap_masks, reference, overlap_seg)
    decoded_overlap = decode_seg_like_host(overlap_seg, uid_to_index, shape)
    decoded_overlap.pop("__unplaced_frames__", None)
    overlap_rows = compare(overlap_masks, decoded_overlap, 1e-3)
    lossless = all(r["dice"] == 1.0 for r in overlap_rows)
    probes.append({
        "probe": "overlapping_structures",
        # `ok` records whether the encoder is lossless here, which it is not.
        # A probe that reported success for a demonstrated defect would be the
        # survivorship bias this evaluation exists to avoid.
        "ok": lossless,
        "expected_lossless": False,
        "detail": {
            "intersection_voxels": intersection,
            "per_structure": overlap_rows,
        },
        "interpretation": (
            "single-labelmap encoding in _export_dicom_seg is lossy for "
            "overlapping structures: the later segment index overwrites the "
            "earlier one and the earlier structure silently loses its shared "
            "voxels. Unreachable via TotalSegmentator's disjoint `total` task, "
            "so it does not affect the cohort result, but it is a latent "
            "defect for any adapter whose seg3d structures may overlap"),
    })

    # -- probe 4: missing SliceThickness ------------------------------------
    # The cohort's source instances omit SliceThickness (0018,0050), which is a
    # Type 2 element a conformant series may leave empty. Reproduced here on a
    # controlled series so the failure is attributable to the tag rather than
    # to anything else about the cohort data.
    stripped = work / "stripped_series"
    if stripped.exists():
        shutil.rmtree(stripped)
    stripped.mkdir(parents=True)
    for path in sorted(series.glob("*.dcm")):
        ds = pydicom.dcmread(str(path))
        del ds.SliceThickness
        pydicom.dcmwrite(stripped / path.name, ds, enforce_file_format=True)

    # Attempted in child processes, once with the pixel-measures fallback and
    # once without. In-process the fallback is already installed and could not
    # be observed; the pair also shows the fallback is what makes the
    # difference rather than something else about the stripped series.
    shim_dir = write_sitecustomize(scratch)
    outcomes: dict[str, dict[str, Any]] = {}
    for label, sandbox in (("without_fallback", False), ("with_fallback", True)):
        code, output, _ = run_subprocess(
            [sys.executable, str(Path(__file__).resolve()),
             "--worker", "probe-thickness", "--series", str(stripped),
             "--output", str(work / f"stripped_{label}.dcm")],
            cwd=REPO_ROOT, env=child_env(shim_dir, scratch, sandbox),
            timeout=900.0)
        message = ""
        for line in output.splitlines():
            if line.startswith("PROBE_RESULT "):
                message = line[len("PROBE_RESULT "):]
        outcomes[label] = {"exit_code": code, "detail": message.strip()[:300]}

    probes.append({
        "probe": "missing_slice_thickness",
        # `ok` describes the SHIPPING adapter, which is the one without the
        # fallback. It fails, and recording that as a pass would hide it.
        "ok": outcomes["without_fallback"]["exit_code"] == 0,
        "expected_lossless": False,
        "detail": {
            "source_has_slice_thickness": False,
            "shipping_adapter": outcomes["without_fallback"],
            "with_eval_fallback": outcomes["with_fallback"],
        },
        "interpretation": (
            "highdicom reads SliceThickness by attribute access while reading "
            "the optional SpacingBetweenSlices with .get(); a source series "
            "that omits the Type 2 SliceThickness therefore raises "
            "AttributeError inside the Segmentation constructor. Every "
            "instance in the CT Lymph Nodes cohort omits it, so the shipping "
            "adapter cannot segment this public collection at all without the "
            "fallback"),
    })

    return probes


