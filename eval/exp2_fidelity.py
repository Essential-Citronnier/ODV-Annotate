def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--worker",
                        choices=["convert", "native", "encode",
                                 "probe-thickness"],
                        help=argparse.SUPPRESS)
    parser.add_argument("--series", type=Path, help=argparse.SUPPRESS)
    parser.add_argument("--input", type=Path, help=argparse.SUPPRESS)
    parser.add_argument("--output", type=Path, help=argparse.SUPPRESS)

    parser.add_argument("--data-root", type=Path,
                        help="directory of tcia_* series directories")
    parser.add_argument("--series-dir", type=Path, action="append", default=[],
                        help="an explicit series directory; repeatable")
    parser.add_argument("--out", type=Path,
                        default=REPO_ROOT / "eval" / "results" / "exp2_fidelity.jsonl")
    parser.add_argument("--csv", type=Path, default=None,
                        help="derived per-structure table (default: --out with .csv)")
    parser.add_argument("--scratch", type=Path,
                        default=REPO_ROOT / ".eval" / "scratch" / "exp2")
    parser.add_argument("--python", default=sys.executable,
                        help="interpreter with TotalSegmentator installed")
    parser.add_argument("--max-cases", type=int, default=None)
    parser.add_argument("--fast", dest="fast", action="store_true", default=True,
                        help="TotalSegmentator fast (3 mm) model (default)")
    parser.add_argument("--no-fast", dest="fast", action="store_false")
    parser.add_argument("--determinism", action="store_true",
                        help="also run the native model twice for a noise floor")
    parser.add_argument("--no-sandbox-substitution", dest="sandbox",
                        action="store_false", default=True,
                        help="run without the sandbox substitutions (see module docstring)")
    parser.add_argument("--probes", action="store_true",
                        help="run the controlled encoder probes before the cohort")
    parser.add_argument("--overlap-check", action="append", default=[],
                        metavar="MASKDIR=SERIESDIR",
                        help="test whether the overlap defect is reachable on "
                             "real cohort output; repeatable")
    parser.add_argument("--probes-only", action="store_true",
                        help="run only the controlled probes (needs no cohort data)")
    parser.add_argument("--keep-intermediates", action="store_true")
    parser.add_argument("--resume", action="store_true",
                        help="skip cases already recorded as ok")
    args = parser.parse_args(argv)

    if args.worker:
        return {"convert": worker_convert, "native": worker_native,
                "encode": worker_encode,
                "probe-thickness": worker_probe_thickness}[args.worker](args)

    if args.overlap_check:
        # Reachability, measured on real cohort output rather than argued from
        # the source: pairs of (native mask dir, source series dir).
        pairs = [tuple(p.split("=", 1)) for p in args.overlap_check]
        report = probe_cohort_overlap([Path(m) for m, _ in pairs],
                                      [Path(s) for _, s in pairs])
        path = args.out.parent / "exp2_overlap_reachability.json"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps({"machine": machine_profile(),
                                    "probe": report}, indent=2) + "\n")
        print(json.dumps(report["detail"], indent=2), flush=True)
        print(f"overlap reachability -> {path}", flush=True)
        return 0

    if args.probes or args.probes_only:
        args.scratch.mkdir(parents=True, exist_ok=True)
        probes = run_probes(args.scratch)
        path = args.out.parent / "exp2_probes.json"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(
            {"experiment": f"{EXPERIMENT}_probes",
             "machine": machine_profile(),
             "probes": probes}, indent=2) + "\n")
        for probe in probes:
            expected = probe.get("expected_lossless", True)
            verdict = ("as expected" if probe["ok"] == expected
                       else "UNEXPECTED")
            print(f"  probe {probe['probe']}: ok={probe['ok']} ({verdict})",
                  flush=True)
        print(f"probes -> {path}", flush=True)
        if args.probes_only:
            return 0

    series: list[Path] = list(args.series_dir)
    if args.data_root:
        series += [p for p in sorted(args.data_root.iterdir())
                   if p.is_dir() and any(p.glob("*.dcm"))]
    series = [p for p in dict.fromkeys(series)]
    if not series:
        parser.error("no series found; pass --data-root or --series-dir")
    if args.max_cases:
        series = series[: args.max_cases]

    args.scratch.mkdir(parents=True, exist_ok=True)
    shim_dir = write_sitecustomize(args.scratch)
    recorder = Recorder(args.out, EXPERIMENT)
    done = recorder.done_case_ids() if args.resume else set()

    print(f"{EXPERIMENT}: {len(series)} series -> {args.out}", flush=True)
    print(f"  accelerator visible: {machine_profile()['gpu_visible']}", flush=True)
    for path in series:
        if path.name in done:
            print(f"  [skip] {path.name}", flush=True)
            continue
        recorder.write(run_case(path, args.scratch, shim_dir, args.python,
                                args.fast, args.sandbox, args.determinism,
                                args.keep_intermediates))

    csv_path = args.csv or args.out.with_suffix(".csv")
    count = write_csv(args.out, csv_path)
    print(f"\nper-structure rows: {count} -> {csv_path}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
