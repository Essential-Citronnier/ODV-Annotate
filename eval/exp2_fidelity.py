def run_case(series_dir: Path, scratch: Path, shim_dir: Path, python: str,
             fast: bool, sandbox: bool, determinism: bool,
             keep: bool) -> CaseResult:
    case_id = series_dir.name
    timer = StageTimer()
    env = child_env(shim_dir, scratch, sandbox)
    work = scratch / case_id
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    notes = [CPU_ONLY_NOTE]
    if sandbox:
        notes += [SANDBOX_NOTE, PIXEL_MEASURES_NOTE]
    peaks: dict[str, float] = {}
    started = time.perf_counter()

    def child(argv: list[str], stage: str, timeout: float = 7200.0) -> str:
        with timer.stage(stage):
            code, output, peak = run_subprocess(
                [python, str(Path(__file__).resolve())] + argv,
                cwd=REPO_ROOT, env=env, timeout=timeout)
        peaks[stage] = peak
        if code != 0:
            tail = "\n".join(output.strip().splitlines()[-12:])
            raise RuntimeError(f"stage {stage} exited {code}:\n{tail}")
        return output

    try:
        # --- shared input -------------------------------------------------
        volume = work / "ct.nii.gz"
        child(["--worker", "convert", "--series", str(series_dir),
               "--output", str(volume)], "convert")

        # --- path B: native ------------------------------------------------
        native_dir = work / "native"
        child(["--worker", "native", "--input", str(volume),
               "--output", str(native_dir)] + (["--fast"] if fast else []),
              "native_inference")
        native_paths = load_native_masks(native_dir)

        # --- (i) determinism control ---------------------------------------
        determinism_rows: list[dict[str, Any]] = []
        if determinism:
            repeat_dir = work / "native_repeat"
            child(["--worker", "native", "--input", str(volume),
                   "--output", str(repeat_dir)] + (["--fast"] if fast else []),
                  "native_inference_repeat")
            repeat_paths = load_native_masks(repeat_dir)
            with timer.stage("compare_determinism"):
                import nibabel as nib

                for name in sorted(set(native_paths) | set(repeat_paths)):
                    a = (np.asanyarray(nib.load(str(native_paths[name])).dataobj) > 0
                         if name in native_paths else None)
                    b = (np.asanyarray(nib.load(str(repeat_paths[name])).dataobj) > 0
                         if name in repeat_paths else None)
                    if a is None:
                        a = np.zeros_like(b)
                    if b is None:
                        b = np.zeros_like(a)
                    if not (a.any() or b.any()):
                        continue
                    determinism_rows.append({
                        "structure": name, "dice": round(dice(a, b), 6),
                        "reference_voxels": int(a.sum()),
                        "candidate_voxels": int(b.sum()),
                        "voxel_delta": int(b.sum()) - int(a.sum()),
                    })

        # --- common frame ---------------------------------------------------
        with timer.stage("geometry"):
            reference_image, uid_to_index, shape = source_geometry(series_dir)
            spacing = reference_image.GetSpacing()
            voxel_ml = float(spacing[0] * spacing[1] * spacing[2]) / 1000.0

        # --- (ii) SEG round trip ---------------------------------------------
        # Encode the native masks with the adapter's exporter and decode with
        # the host's reader. No inference runs between the two, so anything
        # other than 1.0 is the abstraction losing information.
        roundtrip_seg = work / "roundtrip.dcm"
        encode_out = child(["--worker", "encode", "--series", str(series_dir),
                            "--input", str(native_dir),
                            "--output", str(roundtrip_seg)], "seg_encode")
        encoded_structures = None
        for line in encode_out.splitlines():
            try:
                payload = json.loads(line)
            except json.JSONDecodeError:
                continue
            if "encoded_structures" in payload:
                encoded_structures = payload["encoded_structures"]

        with timer.stage("seg_decode_roundtrip"):
            decoded_roundtrip = decode_seg_like_host(roundtrip_seg, uid_to_index, shape)
        unplaced_roundtrip = int(decoded_roundtrip.pop("__unplaced_frames__", 0))

        with timer.stage("resample_native"):
            # The exporter's own input: native masks on the source grid.
            encoder_input = {name: resample_to_source(path, reference_image)
                             for name, path in native_paths.items()}
            encoder_input = {k: v for k, v in encoder_input.items() if v.any()}

        with timer.stage("compare_roundtrip"):
            roundtrip_rows = compare(encoder_input, decoded_roundtrip, voxel_ml)

        # --- (iii) end to end: path A ---------------------------------------
        plugin_dir = work / "plugin"
        plugin_dir.mkdir(parents=True, exist_ok=True)
        # Spawned exactly as PLUGIN_PROTOCOL.md section 4 specifies the host
        # spawns a one-shot adapter: unmodified entry point, --task/--out and
        # --input-<kind> flags, result.json read back from the output dir.
        adapter_argv = [python, str(ADAPTER), "--task", "total",
                        "--out", str(plugin_dir),
                        "--input-series3d", str(series_dir),
                        "--opt-fast", "true" if fast else "false"]
        with timer.stage("plugin_adapter"):
            code, adapter_output, peak = run_subprocess(
                adapter_argv, cwd=REPO_ROOT, env=env, timeout=7200.0)
        peaks["plugin_adapter"] = peak

        result_json = plugin_dir / "result.json"
        adapter_result = (json.loads(result_json.read_text())
                          if result_json.exists() else None)
        if code != 0 or not adapter_result or not adapter_result.get("ok"):
            detail = (adapter_result or {}).get("error", {})
            tail = "\n".join(adapter_output.strip().splitlines()[-8:])
            raise RuntimeError(
                f"plugin adapter exited {code}; result.json error="
                f"{detail.get('code')}: {detail.get('message')}\n{tail}")

        plugin_seg = plugin_dir / adapter_result["outputs"]["seg3d"]
        with timer.stage("seg_decode_plugin"):
            decoded_plugin = decode_seg_like_host(plugin_seg, uid_to_index, shape)
        unplaced_plugin = int(decoded_plugin.pop("__unplaced_frames__", 0))

        with timer.stage("compare_end_to_end"):
            end_to_end_rows = compare(encoder_input, decoded_plugin, voxel_ml)

        metrics: dict[str, Any] = {
            "series_dir": str(series_dir),
            "slices": shape[0],
            "grid": list(shape),
            "voxel_ml": round(voxel_ml, 8),
            "fast": fast,
            "native_structures_nonempty": len(encoder_input),
            "native_structures_written": len(native_paths),
            "encoded_structures": encoded_structures,
            "plugin_seg_bytes": plugin_seg.stat().st_size,
            "roundtrip_seg_bytes": roundtrip_seg.stat().st_size,
            "adapter_elapsed_ms": adapter_result.get("elapsed_ms"),
            "unplaced_frames_roundtrip": unplaced_roundtrip,
            "unplaced_frames_plugin": unplaced_plugin,
            "roundtrip": summarise(roundtrip_rows),
            "end_to_end": summarise(end_to_end_rows),
            "determinism": summarise(determinism_rows) if determinism_rows else None,
            "per_structure_roundtrip": roundtrip_rows,
            "per_structure_end_to_end": end_to_end_rows,
            "per_structure_determinism": determinism_rows,
        }
        result = CaseResult(
            experiment=EXPERIMENT, case_id=case_id, ok=True,
            wall_s=round(time.perf_counter() - started, 2),
            stages_s={k: round(v, 2) for k, v in timer.stages.items()},
            peak_rss_bytes=max(peaks.values()) if peaks else None,
            metrics=metrics, notes=notes)
    except Exception as exc:  # noqa: BLE001 -- a failed case is a recorded case
        result = CaseResult(
            experiment=EXPERIMENT, case_id=case_id, ok=False,
            wall_s=round(time.perf_counter() - started, 2),
            stages_s={k: round(v, 2) for k, v in timer.stages.items()},
            peak_rss_bytes=max(peaks.values()) if peaks else None,
            metrics={"series_dir": str(series_dir)},
            error=f"{type(exc).__name__}: {exc}", notes=notes)
    finally:
        if not keep and work.exists():
            # A SEG for 80 structures over 400 slices is ~300 MB; keeping every
            # case's intermediates would cost tens of gigabytes for no reuse.
            shutil.rmtree(work, ignore_errors=True)
    return result


